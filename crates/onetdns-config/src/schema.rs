/** @brief 설정 항목 하나의 메타데이터. */
pub struct Field {
    /** @brief 설정 항목 이름. */
    pub key: &'static str,
    /** @brief 값의 형. */
    pub kind: &'static str,
    /** @brief 대시보드에서 묶어 보일 분류. */
    pub group: &'static str,
    /** @brief 화면에 보일 이름. */
    pub label: &'static str,
    /** @brief 형에 딸린 부가 정보. 고를 값 목록 같은 것. */
    pub meta: &'static str,
}

/** @brief 항목 하나를 만든다. 상수 문맥에서 테이블을 채운다. */
const fn f(
    key: &'static str,
    kind: &'static str,
    group: &'static str,
    label: &'static str,
    meta: &'static str,
) -> Field {
    Field {
        key,
        kind,
        group,
        label,
        meta,
    }
}

/** @brief 모든 항목. */
pub fn fields() -> &'static [Field] {
    FIELDS
}

